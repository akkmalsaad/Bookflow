/**
 * BookFlow's interface language.
 *
 * Deliberately a small hand-written dictionary rather than an i18n library: only the Home screen is
 * translated so far, the app has no plural or gender rules to resolve, and adding a dependency for
 * a lookup table would be more to maintain than the table itself.
 *
 * Bahasa Melayu as used in Malaysia — not Bahasa Indonesia.
 */

export type Locale = 'en' | 'ms-MY';

