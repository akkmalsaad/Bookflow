const TRANSLATIONS: Record<Locale, Record<TranslationKey, string>> = {
  en: HOME_EN,
  'ms-MY': HOME_MS,
};

export type Translate = (key: TranslationKey, values?: Record<string, string | number>) => string;

/**
 * Looks a key up in the active locale, falling back to English so a missing translation shows real
 * words rather than a key. `{placeholders}` are filled from `values`.
 */
export function translate(locale: Locale, key: TranslationKey, values?: Record<string, string | number>) {
  const template = TRANSLATIONS[locale]?.[key] ?? TRANSLATIONS.en[key] ?? key;
  if (!values) return template;

  return Object.entries(values).reduce(
    (text, [name, value]) => text.replace(new RegExp(`\\{${name}\\}`, 'g'), String(value)),
    template,
  );
}

/**
 * The BCP 47 tag for `Intl`. Malay day and month names come from the platform's own data, so dates
 * read naturally without a second list of month names to maintain.
 */
export function getIntlLocale(locale: Locale) {
  return locale === 'ms-MY' ? 'ms-MY' : 'en-GB';
}

